using Snap.Hutao.Remastered.Core.Property;

namespace Snap.Hutao.Remastered.Test.RuntimeBehavior;

[TestClass]
public sealed class ReadOnlyObservablePropertyBindingTest
{
    [TestMethod]
    public void CompiledBindingCanReadTheReadOnlyValueFromNotificationSender()
    {
        ObservableProperty<bool> source = new(true);
        IReadOnlyObservableProperty<bool> view = new ObservablePropertyReadOnlyWrapper<bool>(source);
        bool displayedConnected = view.Value;
        object? notificationSender = null;
        view.PropertyChanged += (sender, args) =>
        {
            notificationSender = sender;
            // This is the sender cast in LaunchGamePage.g.cs generated by x:Bind.
            if (args.PropertyName is null or "" or "Value" && sender is IReadOnlyObservableProperty<bool> changed)
            {
                displayedConnected = changed.Value;
            }
        };

        source.Value = false;
        Assert.AreSame(view, notificationSender);
        Assert.IsFalse(displayedConnected);
        source.Value = true;
        Assert.IsTrue(displayedConnected);
    }

    [TestMethod]
    public void IndependentReadOnlyViewsKeepTheirOwnSenderAndSupportUnsubscription()
    {
        ObservableProperty<int> source = new(1);
        IReadOnlyObservableProperty<int> first = new ObservablePropertyReadOnlyWrapper<int>(source);
        IReadOnlyObservableProperty<int> second = new ObservablePropertyReadOnlyWrapper<int>(source);
        int firstNotifications = 0;
        int secondNotifications = 0;
        PropertyChangedEventHandler handler = (sender, _) => { Assert.AreSame(first, sender); firstNotifications++; };
        first.PropertyChanged += handler;
        second.PropertyChanged += (sender, _) => { Assert.AreSame(second, sender); secondNotifications++; };
        source.Value = 2;
        first.PropertyChanged -= handler;
        using (source.GetDeferral()) { source.Value = 3; source.Value = 4; }
        Assert.AreEqual(1, firstNotifications);
        Assert.AreEqual(2, secondNotifications);
        Assert.AreEqual(4, second.Value);
    }
}

